// Release signing key lives outside version control, see keystore/keystore.properties.
val keystoreDir = rootProject.file("keystore")
val keystoreProperties = Properties().apply {
    val file = keystoreDir.resolve("keystore.properties")
    if (file.exists()) file.inputStream().use(::load)
}

android {
    namespace = "com.fredypot"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.fredypot"
        minSdk = 29
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (!keystoreProperties.isEmpty) {
            create("release") {
                storeFile = keystoreDir.resolve(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            optimization {
                enable = true
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
}

